"""
Real Python tools exposed to the fact-checker agent via function calling.

- verify_calculation: sympy-backed math checking, so the LLM never does mental math.
- search_reference_material: keyword search over teacher-uploaded lecture notes,
  scoped server-side to the question set being graded.

SECURITY: tool arguments are generated by an LLM that has read untrusted student
text, so they are treated as hostile input. sympy's parser uses eval(), hence the
strict allowlist + resource guards below.
"""
import asyncio
import re
from typing import Any

import sympy
from sympy.parsing.sympy_parser import (
    convert_xor,
    implicit_multiplication_application,
    parse_expr,
    standard_transformations,
)

# ─────────────────────────── verify_calculation ───────────────────────────

_ALLOWED_NAMES: dict[str, Any] = {
    "sqrt": sympy.sqrt, "cbrt": sympy.cbrt, "root": sympy.root,
    "sin": sympy.sin, "cos": sympy.cos, "tan": sympy.tan,
    "asin": sympy.asin, "acos": sympy.acos, "atan": sympy.atan,
    "sinh": sympy.sinh, "cosh": sympy.cosh, "tanh": sympy.tanh,
    "log": sympy.log, "ln": sympy.log, "exp": sympy.exp,
    "abs": sympy.Abs, "Abs": sympy.Abs, "factorial": sympy.factorial,
    "floor": sympy.floor, "ceiling": sympy.ceiling,
    "pi": sympy.pi, "E": sympy.E, "e": sympy.E, "oo": sympy.oo,
    "diff": sympy.diff, "integrate": sympy.integrate, "limit": sympy.limit,
    "simplify": sympy.simplify, "expand": sympy.expand, "factor": sympy.factor,
    "solve": sympy.solve, "Rational": sympy.Rational,
}
_ALLOWED_CHARS = re.compile(r"^[0-9A-Za-z_+\-*/^().,=<>\s]+$")
_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_SYMBOL = re.compile(r"^[A-Za-z][0-9]?$")  # x, y, t, x1 ...
_MAX_LEN = 300
_MAX_EXPONENT = 1000
_MAX_FACTORIAL = 500
_TIMEOUT_S = 3.0
_TRANSFORMS = standard_transformations + (implicit_multiplication_application, convert_xor)


class UnsafeExpression(ValueError):
    pass


def _validate_source(expr: str) -> dict[str, Any]:
    if len(expr) > _MAX_LEN:
        raise UnsafeExpression(f"expression longer than {_MAX_LEN} chars")
    if not _ALLOWED_CHARS.match(expr):
        raise UnsafeExpression("expression contains disallowed characters")
    if "__" in expr or re.search(r"\.(?!\d)", expr) or re.search(r"\d{40,}", expr):
        raise UnsafeExpression("expression contains a disallowed pattern")

    local_dict: dict[str, Any] = {}
    for name in set(_IDENTIFIER.findall(expr)):
        if name in _ALLOWED_NAMES:
            local_dict[name] = _ALLOWED_NAMES[name]
        elif _SYMBOL.match(name):
            local_dict[name] = sympy.Symbol(name)
        else:
            raise UnsafeExpression(f"identifier '{name}' is not allowed")
    return local_dict


def _guard_resources(node: sympy.Basic) -> None:
    """Reject exponent/factorial bombs (e.g. 9**9**9) before evaluation."""
    for sub in sympy.preorder_traversal(node):
        if isinstance(sub, sympy.Pow):
            if sub.exp.is_Number and abs(sub.exp) > _MAX_EXPONENT:
                raise UnsafeExpression("exponent too large")
            if isinstance(sub.exp, sympy.Pow) or isinstance(sub.base, sympy.Pow):
                raise UnsafeExpression("nested exponents are not allowed")
        if getattr(sub, "func", None) is not None and str(sub.func) == "factorial":
            if sub.args and sub.args[0].is_Number and sub.args[0] > _MAX_FACTORIAL:
                raise UnsafeExpression("factorial argument too large")


def _parse(src: str, local_dict: dict[str, Any]) -> sympy.Basic:
    # Pass 1: every function is an inert placeholder and operators are left
    # unevaluated, so nothing expensive runs before the resource guard.
    inert = {
        k: (sympy.Function(k) if callable(v) and not isinstance(v, sympy.Basic) else v)
        for k, v in local_dict.items()
    }
    _guard_resources(parse_expr(src, local_dict=inert, transformations=_TRANSFORMS, evaluate=False))
    # Pass 2: real evaluation
    return parse_expr(src, local_dict=local_dict, transformations=_TRANSFORMS)


def _numeric(value: sympy.Basic) -> str | None:
    try:
        if getattr(value, "is_number", False):
            return str(sympy.N(value, 10))
    except Exception:
        pass
    return None


def _verify_sync(expression: str) -> dict:
    expression = expression.strip()
    local_dict = _validate_source(expression)

    # Equation check: "lhs = rhs" (a single '=', not '<=', '>=' or '==')
    parts = re.split(r"(?<![<>=])=(?!=)", expression)
    if len(parts) == 2:
        lhs, rhs = (_parse(p, local_dict) for p in parts)
        difference = sympy.simplify(lhs - rhs)
        equal = difference == 0
        approx = equal
        if not equal and difference.is_number:
            scale = max(1.0, abs(float(sympy.N(rhs))) if rhs.is_number else 1.0)
            gap = abs(float(sympy.N(difference)))
            equal = gap < 1e-9 * scale
            approx = gap <= 5e-3 * scale  # tolerate student rounding (0.5%)
        return {
            "expression": expression,
            "kind": "equation",
            "holds": bool(equal),
            "approximately_equal": bool(approx),
            "lhs": str(sympy.simplify(lhs)),
            "rhs": str(sympy.simplify(rhs)),
            "lhs_numeric": _numeric(lhs),
            "rhs_numeric": _numeric(rhs),
        }
    if len(parts) > 2:
        raise UnsafeExpression("only one '=' is allowed")

    value = _parse(expression, local_dict)
    if isinstance(value, sympy.logic.boolalg.BooleanAtom) or getattr(value, "is_Relational", False):
        return {"expression": expression, "kind": "inequality", "holds": bool(value)}
    return {
        "expression": expression,
        "kind": "expression",
        "result": str(value),
        "numeric": _numeric(value),
    }


async def verify_calculation(expression: str) -> dict:
    """Evaluate/verify a math expression safely, with a wall-clock timeout."""
    try:
        return await asyncio.wait_for(asyncio.to_thread(_verify_sync, expression), _TIMEOUT_S)
    except asyncio.TimeoutError:
        return {"expression": expression, "error": "evaluation timed out"}
    except UnsafeExpression as e:
        return {"expression": expression, "error": f"rejected: {e}"}
    except Exception as e:  # sympy syntax errors etc.
        return {"expression": expression, "error": f"could not evaluate: {type(e).__name__}"}


# ───────────────────────── search_reference_material ─────────────────────────

_MAX_RESULTS = 3
_MAX_SNIPPET = 1200
_WORD = re.compile(r"[a-z0-9]{3,}")


async def has_reference_material(question_set_id) -> bool:
    from app.db.database import ReferenceChunk
    return await ReferenceChunk.find({"question_set_id": question_set_id}).count() > 0


async def search_reference_material(question_set_id, query: str, student_only: bool = False) -> dict:
    """
    MongoDB $text search over this question set's uploaded material, with a
    keyword-overlap fallback if the text index is unavailable.
    `student_only` restricts results to sources the teacher shared with students.
    """
    from app.db.database import ReferenceChunk

    query = (query or "")[:300]
    scope: dict = {"question_set_id": question_set_id}
    if student_only:
        scope["student_visible"] = True
    hits: list[dict] = []
    try:
        hits = await ReferenceChunk.aggregate([
            {"$match": {**scope, "$text": {"$search": query}}},
            {"$addFields": {"score": {"$meta": "textScore"}}},
            {"$sort": {"score": -1}},
            {"$limit": _MAX_RESULTS},
        ]).to_list()
    except Exception as e:
        print(f"Text search unavailable, using keyword fallback: {e}")
        terms = set(_WORD.findall(query.lower()))
        chunks = await ReferenceChunk.find(scope).limit(300).to_list()
        scored = []
        for c in chunks:
            overlap = len(terms & set(_WORD.findall(c.content.lower())))
            if overlap:
                scored.append({"source_name": c.source_name, "content": c.content, "score": overlap})
        hits = sorted(scored, key=lambda h: h["score"], reverse=True)[:_MAX_RESULTS]

    return {
        "query": query,
        "results": [
            {"source": h.get("source_name"), "excerpt": h.get("content", "")[:_MAX_SNIPPET]}
            for h in hits
        ],
    }


# ───────────────────────── OpenAI-style tool schemas ─────────────────────────

MAX_EXPRESSIONS_PER_CALL = 8


async def verify_calculations(expressions: list[str]) -> dict:
    """Batch form used by the fact-checker: one tool call checks all of a student's working."""
    return {"results": [await verify_calculation(str(e)) for e in expressions[:MAX_EXPRESSIONS_PER_CALL]]}


VERIFY_CALCULATION_SCHEMA = {
    "type": "function",
    "function": {
        "name": "verify_calculation",
        "description": (
            "Verify numerical or symbolic steps with a computer algebra system. Pass ALL the "
            "student's calculations at once in `expressions`: each is an expression to evaluate "
            "(e.g. '3*4.5 + 2^3', 'diff(x^3, x)') or an equation to check (e.g. '2*x + 3 = 11' "
            "with x substituted, or 'integrate(2*x, x) = x^2')."
        ),
        "parameters": {
            "type": "object",
            "properties": {
                "expressions": {
                    "type": "array",
                    "items": {"type": "string", "description": "sympy-compatible math"},
                    "maxItems": MAX_EXPRESSIONS_PER_CALL,
                },
            },
            "required": ["expressions"],
        },
    },
}

