from datetime import datetime
from typing import Optional, Annotated, List
from beanie import Document, init_beanie, Link, Indexed, PydanticObjectId
from motor.motor_asyncio import AsyncIOMotorClient
from pydantic import EmailStr, Field
from pymongo import IndexModel, TEXT
from app.core.config import settings

class User(Document):
    username: Annotated[str, Indexed(unique=True)]
    email: Optional[EmailStr] = None
    hashed_password: Optional[str] = None
    role: str

    class Settings:
        name = "users"

class QuestionSet(Document):
    title: str
    question: str
    model_answer: str
    creator: Link[User]
    assigned_students: List[Link[User]] = []
    # Atomic rubric generated by the Rubric Decomposer agent, cached so it is
    # produced once per question rather than once per submission.
    rubric_criteria: Optional[List[dict]] = None
    # Hash of the model answer the rubric was generated from (cache invalidation)
    rubric_hash: Optional[str] = None

    class Settings:
        name = "question_sets"

class Submission(Document):
    question_set: Link[QuestionSet]
    student: Link[User]
    student_answer: str
    ai_score: int
    ai_feedback: str
    final_score: Optional[int] = None
    # Full audit trail of the grading graph: node path, per-criterion scores,
    # confidence, tool calls, critic verdict. Visible to teachers only.
    grading_trace: Optional[dict] = None

    class Settings:
        name = "submissions"

class ReferenceChunk(Document):
    """A chunk of teacher-uploaded lecture notes / PDFs for one question set."""
    question_set_id: Annotated[PydanticObjectId, Indexed()]
    source_name: str
    chunk_index: int
    content: str

    class Settings:
        name = "reference_chunks"
        indexes = [IndexModel([("content", TEXT)], name="content_text")]

class ApiToken(Document):
    """Personal access token for MCP clients. Only the SHA-256 hash is stored."""
    user_id: Annotated[PydanticObjectId, Indexed()]
    name: str
    token_hash: Annotated[str, Indexed(unique=True)]
    prefix: str  # first characters, so users can tell tokens apart
    role: str    # role at creation time; a role change invalidates the token
    created_at: datetime
    expires_at: Optional[datetime] = None
    last_used_at: Optional[datetime] = None
    revoked_at: Optional[datetime] = None

    class Settings:
        name = "api_tokens"

async def init_db():
    client = AsyncIOMotorClient(settings.DATABASE_URL)
    await init_beanie(
        database=client.get_default_database(),
        document_models=[User, QuestionSet, Submission, ReferenceChunk, ApiToken]
    )
    print("Database initialized successfully with all models.")
